from __future__ import annotations

import threading

from database.connection import transaction

_LOCK = threading.RLock()
_READY = False

_RUNTIME_DDL = [
    """CREATE TABLE IF NOT EXISTS task_runs (
        task_id TEXT PRIMARY KEY, task_type TEXT NOT NULL, status TEXT NOT NULL,
        owner_id TEXT NOT NULL DEFAULT '', session_id TEXT NOT NULL DEFAULT '',
        request_json TEXT NOT NULL, metadata_json TEXT NOT NULL DEFAULT '{}',
        result_json TEXT, error_json TEXT, progress DOUBLE PRECISION NOT NULL DEFAULT 0,
        message TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, started_at TEXT,
        finished_at TEXT, updated_at TEXT NOT NULL, timeout_seconds BIGINT NOT NULL DEFAULT 99600,
        max_retries BIGINT NOT NULL DEFAULT 0, attempt BIGINT NOT NULL DEFAULT 0,
        cancel_requested BIGINT NOT NULL DEFAULT 0, worker_pid BIGINT, acknowledged_at TEXT
    )""",
    "CREATE INDEX IF NOT EXISTS idx_task_runs_lookup ON task_runs(owner_id, session_id, task_type, created_at DESC)",
    "CREATE INDEX IF NOT EXISTS idx_task_runs_status ON task_runs(status, updated_at DESC)",
    """CREATE TABLE IF NOT EXISTS task_events (
        sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        task_id TEXT NOT NULL REFERENCES task_runs(task_id), event_type TEXT NOT NULL,
        data_json TEXT NOT NULL DEFAULT '{}', created_at TEXT NOT NULL
    )""",
    "CREATE INDEX IF NOT EXISTS idx_task_events_task ON task_events(task_id, sequence)",
]


def ensure_runtime_schema() -> None:
    global _READY
    if _READY:
        return
    with _LOCK:
        if _READY:
            return
        with transaction(runtime=True) as conn:
            # PostgreSQL Advisory Lock（顾问锁）跨进程序列化 Runtime Schema 初始化。
            # Python threading lock 只能保护单进程；API 与 docker exec/Worker
            # 可能在不同进程同时启动，因此 CREATE INDEX IF NOT EXISTS 仍可能
            # 在 PostgreSQL catalog（系统目录）层发生竞态。
            conn.execute(
                "SELECT pg_advisory_xact_lock(%s)",
                (836080806,),
            )
            for statement in _RUNTIME_DDL:
                conn.execute(statement)
        _READY = True
